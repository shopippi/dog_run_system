// お客さん向けの「使い方・よくある質問」の文章。
// 文章を変えるときはここだけを直す。ポイント数など設定で変わる値は、引数から入れる。

export type HelpItem = {
  /** 質問(行の見出し) */
  q: string;
  /** 答え(段落ごと) */
  a: string[];
};

export type HelpContext = {
  /** 無料券1枚に必要なポイント数(管理画面の設定) */
  pointsPerTicket: number;
};

export function helpItems({ pointsPerTicket }: HelpContext): HelpItem[] {
  return [
    {
      q: 'ポイントはどうやってたまりますか?',
      a: [
        '受付のQRコードを、会員証の「チェックイン」から読み取ると、1ポイントたまります。',
        'ポイントはおうちごとに1日1ポイントです。ワンちゃんが何頭いても、家族の誰がチェックインしても、1日1ポイントです。',
        '家族の誰かがその日にチェックインしているときは、一緒に来たワンちゃんを追加するだけになります(ポイントは増えません)。',
      ],
    },
    {
      q: '無料券はどうやって使いますか?',
      a: [
        `${pointsPerTicket}ポイントたまると、無料券が1枚もらえます(来場1回分が無料)。もらった無料券は、次の来場から使えます。`,
        'チェックインのときに「無料券を使う」を選んでください。完了の画面に「無料券を使用」と出るので、受付でその画面を見せてください。',
        '無料券を使った日も、ポイントは1ポイントたまります。',
      ],
    },
    {
      q: '家族も同じ会員証を使えますか?',
      a: [
        '使えます。会員証の「家族を招待」から、LINEのトークで招待を送るか、招待のQRコードをご家族に読み取ってもらってください。',
        'ご家族が参加すると、誰がチェックインしても同じ会員証にポイントがたまります。招待は24時間有効で、1回だけ使えます。',
        'ご家族がすでに別の会員証でポイントをためているときは、管理者が確認してから1つにまとめます。',
      ],
    },
    {
      q: 'ワンちゃんの写真や名前を変えたい',
      a: [
        '会員証の「ワンちゃん」から、変えたいワンちゃんを選んでください。写真・名前・性別・生まれた年月を変えられます。',
        '犬種とサイズは、受付で変えます。間違っているときは受付にお知らせください。',
      ],
    },
    {
      q: '前のポイントカードのポイントを引き継げますか?',
      a: [
        'LINEのショップカードと紙のスタンプカードのポイントを、引き継げます。会員証の「旧カードの引き継ぎ」から、カードの写真を付けて申請してください。',
        '管理者が写真を確認すると、会員証のポイントに加わります。カードの種類ごとに1回ずつ申請できます。',
        '受付でカードを見せて、引き継いでもらうこともできます。',
      ],
    },
    {
      q: '困ったときは?',
      a: [
        '会員証が開かない、ポイントが合わない、家族のつなぎ方が分からないなど、困ったときは受付のスタッフにお知らせください。',
        'スマホを忘れた日も、受付でチェックインできます。',
      ],
    },
  ];
}
