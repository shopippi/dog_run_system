/** お知らせの文の例(LINEの一斉配信・店頭のPOP)。施設名はあとで差し込む */
export function announcementText(facility: string, period: { start: string | null; end: string | null }): string {
  const md = (d: string | null) => (d ? `${Number(d.slice(5, 7))}月${Number(d.slice(8, 10))}日` : '○月○日');
  return [
    `【${facility}】会員証が新しくなります`,
    '',
    `${md(period.start)}から、LINEの中の新しい会員証でポイントがたまるようになります。ご家族のLINEが別々でも、同じおうちとしてポイントがまとまります。`,
    '',
    '■ はじめての方',
    '受付のQRコードをLINEで読み取ると、1分ほどで登録できます(ワンちゃんの写真もどうぞ)。',
    '',
    '■ 前のカードのポイント',
    `${md(period.end)}までに、受付で前のカード(LINEのショップカード・紙のカード)を見せてください。たまっているポイントを新しい会員証に引き継げます。`,
    '',
    `${md(period.end)}を過ぎると、前のカードのポイントは引き継げなくなります。`,
  ].join('\n');
}
